    private void btnSaveOrderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveOrderActionPerformed
        // TODO add your handling code here:
        // 1. Basic Validation
    if (txtCustomerName.getText().isEmpty() || tblCart.getRowCount() == 0) {
        JOptionPane.showMessageDialog(this, "Please select a customer and add items to the cart!");
        return;
    }

    try {
        // 2. Prepare Order Object
        com.inventory.model.Order order = new com.inventory.model.Order();
        int customerRow = tblCustomer.getSelectedRow();
        int customerId = Integer.parseInt(tblCustomer.getValueAt(customerRow, 0).toString());
        order.setCustomerId(customerId);
        
        // Extract numerical total (e.g., "Total Amount RS: 500.0" -> 500.0)
        String totalText = lblTotalAmount.getText().replaceAll("[^0-9.]", "");
        order.setTotalAmount(Double.parseDouble(totalText));

        // 3. Save Order to Database
        com.inventory.dao.OrderDAO orderDao = new com.inventory.dao.OrderDAO();
        DefaultTableModel cartModel = (DefaultTableModel) tblCart.getModel();
        int generatedOrderId = orderDao.saveOrder(order, cartModel);

        if (generatedOrderId != -1) {
            com.inventory.dao.ProductDAO pDao = new com.inventory.dao.ProductDAO();
            
            for (int i = 0; i < cartModel.getRowCount(); i++) {
                // Get data from the cart table
                int pId = Integer.parseInt(cartModel.getValueAt(i, 0).toString());
                String pName = cartModel.getValueAt(i, 1).toString();
                int qtyToSubtract = Integer.parseInt(cartModel.getValueAt(i, 2).toString());

                // 4. Proactive Threshold Check using your specific variable names
                com.inventory.model.Product p = pDao.getProductById(pId); 
                
                // Using your specific variables: currentQuantity and minThreshold
                int stockAfterSale = p.getCurrentQuantity() - qtyToSubtract;

                if (stockAfterSale <= p.getMinThreshold()) {
                    JOptionPane.showMessageDialog(this, "CRITICAL: " + pName + 
                        " is now at " + stockAfterSale + " units. Please restock immediately!");
                }

                // 5. Update the stock in the database
                pDao.updateStock(pId, qtyToSubtract);
            }

            // 6. Finalize UI
            JOptionPane.showMessageDialog(this, "Order #" + generatedOrderId + " Saved Successfully!");
            generatePDF(generatedOrderId); 
            btnResetActionPerformed(null); 
            loadTables(); 
            
        } else {
            JOptionPane.showMessageDialog(this, "Failed to create Order record in Database.");
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        e.printStackTrace();
    }
    }//GEN-LAST:event_btnSaveOrderActionPerformed
