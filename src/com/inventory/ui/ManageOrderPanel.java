    private void tblCustomerMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCustomerMouseClicked
        // TODO add your handling code here:
        int row = tblCustomer.getSelectedRow();
    if (row != -1) {
        int id = (int) tblCustomer.getValueAt(row, 0);
        
        // Find the full customer details from the DAO using the ID
        List<Customer> customers = new CustomerDAO().getAllCustomers();
        for(Customer c : customers) {
            if(c.getCustomerId() == id) {
                txtCustomerName.setText(c.getName());
                txtCustomerMobile.setText(c.getMobile());
                break;
            }
        }
    }
    }//GEN-LAST:event_tblCustomerMouseClicked

    private void loadTables() {
    // 1. Setup Customer Table (ID, Name, Address)
    DefaultTableModel custModel = (DefaultTableModel) tblCustomer.getModel();
    custModel.setRowCount(0); // Clear table first
    
    try {
        List<com.inventory.model.Customer> customers = new com.inventory.dao.CustomerDAO().getAllCustomers();
        for (com.inventory.model.Customer c : customers) {
            custModel.addRow(new Object[]{
                c.getCustomerId(), 
                c.getName(), 
                c.getAddress() // Showing Address as per your requirement
            });
        }
    } catch (Exception e) {
        System.out.println("Error loading customers: " + e.getMessage());
    }

    // 2. Setup Product Table (ID, Name, Price, Quantity)
    DefaultTableModel prodModel = (DefaultTableModel) tblProduct.getModel();
    prodModel.setRowCount(0); // Clear table first
    
    try {
        List<com.inventory.model.Product> products = new com.inventory.dao.ProductDAO().getAllProducts();
        for (com.inventory.model.Product p : products) {
            prodModel.addRow(new Object[]{
                p.getProductId(), 
                p.getName(), 
                p.getPrice(), 
                p.getCurrentQuantity() // Shows current stock
            });
        }
    } catch (Exception e) {
        System.out.println("Error loading products: " + e.getMessage());
    }
}
    
    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
        String searchMobile = txtSearch.getText().trim();
    
    if (searchMobile.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please enter a mobile number to search.");
        return;
    }

    boolean found = false;
    List<Customer> customers = new CustomerDAO().getAllCustomers();

    for (Customer c : customers) {
        if (c.getMobile().equals(searchMobile)) {
            // Fill the display fields
            txtCustomerName.setText(c.getName());
            txtCustomerMobile.setText(c.getMobile());
            
            // Highlight the customer in the table for visual confirmation
            for (int i = 0; i < tblCustomer.getRowCount(); i++) {
                if ((int)tblCustomer.getValueAt(i, 0) == c.getCustomerId()) {
                    tblCustomer.setRowSelectionInterval(i, i);
                    break;
                }
            }
            found = true;
            break;
        }
    }

    if (!found) {
        int response = JOptionPane.showConfirmDialog(this, 
            "Customer not found. Would you like to add a new record for " + searchMobile + "?", 
            "Not Found", JOptionPane.YES_NO_OPTION);

        if (response == JOptionPane.YES_OPTION) {
            String name = JOptionPane.showInputDialog(this, "Enter Full Name:");
            if (name != null && !name.isEmpty()) {
                String email = JOptionPane.showInputDialog(this, "Enter Email:");
                String address = JOptionPane.showInputDialog(this, "Enter Address:");

                Customer newCust = new Customer();
                newCust.setName(name);
                newCust.setMobile(searchMobile);
                newCust.setEmail(email);
                newCust.setAddress(address);

                if (new CustomerDAO().addCustomer(newCust)) {
                    loadTables(); // Refresh to show new customer address in table
                    txtCustomerName.setText(name);
                    txtCustomerMobile.setText(searchMobile);
                }
            }
        }
    }
    }//GEN-LAST:event_btnSearchActionPerformed

