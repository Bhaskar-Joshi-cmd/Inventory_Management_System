    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        int index = tblUsers.getSelectedRow();
        if (index == -1) {
            JOptionPane.showMessageDialog(this, "Select a user to delete!");
            return;
        }

        int a = JOptionPane.showConfirmDialog(this, "Delete this user?", "Confirm", JOptionPane.YES_NO_OPTION);
        if (a == JOptionPane.YES_OPTION) {
            int id = (Integer) tblUsers.getValueAt(index, 0);
            if (new UserDAO().deleteUser(id)) {
                JOptionPane.showMessageDialog(this, "User deleted!");
                loadTableData();
                clearFields();
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        int index = tblUsers.getSelectedRow();
        if (index == -1) {
            JOptionPane.showMessageDialog(this, "Select a user to update!");
            return;
        }

        User updatedUser = new User();
        updatedUser.setUserId((Integer) tblUsers.getValueAt(index, 0));
        updatedUser.setUsername(txtName.getText().trim());
        updatedUser.setEmail(txtEmail.getText().trim());
        updatedUser.setRole(comboRole.getSelectedItem().toString());
        updatedUser.setStatus(comboStatus.getSelectedItem().toString());

        if (new UserDAO().updateUser(updatedUser)) {
            JOptionPane.showMessageDialog(this, "User updated successfully!");
            loadTableData();
            clearFields();
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void tblUsersMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblUsersMouseClicked
        // TODO add your handling code here:
        int index = tblUsers.getSelectedRow();
        if (index == -1) return;

        txtName.setText(tblUsers.getValueAt(index, 1).toString());
        txtEmail.setText(tblUsers.getValueAt(index, 2).toString());
        comboRole.setSelectedItem(tblUsers.getValueAt(index, 3).toString());
        comboStatus.setSelectedItem(tblUsers.getValueAt(index, 4).toString());

        txtPassword.setEnabled(false); // Security: Don't show/edit password on update
        btnAddUser.setEnabled(false);
    }//GEN-LAST:event_tblUsersMouseClicked
        private void loadTableData() {
        DefaultTableModel dtm = (DefaultTableModel) tblUsers.getModel();
        dtm.setRowCount(0);
        
        UserDAO userDAO = new UserDAO();
        List<User> list = userDAO.getAllUsers();
        
        for (User user : list) {
            dtm.addRow(new Object[]{
                user.getUserId(),
                user.getUsername(),
                user.getEmail(),
                user.getRole(),
                user.getStatus()
            });
        }
    }

    private void setupTableUI() {
        DefaultTableCellRenderer centerRenderer = new DefaultTableCellRenderer();
        centerRenderer.setHorizontalAlignment(JLabel.CENTER);
        
        for (int i = 0; i < tblUsers.getColumnCount(); i++) {
            tblUsers.getColumnModel().getColumn(i).setCellRenderer(centerRenderer);
        }
        ((DefaultTableCellRenderer)tblUsers.getTableHeader().getDefaultRenderer())
            .setHorizontalAlignment(JLabel.CENTER);
        
        tblUsers.setRowHeight(25);
    }
    private void clearFields() {
        txtName.setText("");
        txtEmail.setText("");
        txtPassword.setText("");
        comboRole.setSelectedIndex(0);
        comboStatus.setSelectedIndex(0);
        txtPassword.setEnabled(true);
        btnAddUser.setEnabled(true);
        tblUsers.clearSelection();
    }

