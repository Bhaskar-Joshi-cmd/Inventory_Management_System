    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        int row = tblCustomers.getSelectedRow();
    if (row == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Select a customer to update!");
        return;
    }

    com.inventory.model.Customer c = new com.inventory.model.Customer();
    c.setCustomerId((int) tblCustomers.getValueAt(row, 0));
    c.setName(txtCustomerName.getText().trim());
    c.setMobile(txtMobile.getText().trim());
    c.setEmail(txtEmail.getText().trim());
    c.setAddress(txtAddress.getText().trim());

    if (new com.inventory.dao.CustomerDAO().updateCustomer(c)) {
        javax.swing.JOptionPane.showMessageDialog(this, "Customer Updated!");
        loadTableData();
        clearFields();
    }
    }//GEN-LAST:event_btnUpdateActionPerformed

