    private void btnAddToCartActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddToCartActionPerformed
        // TODO add your handling code here:
        
    // 1. Validation: Check if a customer is selected
    if (txtCustomerName.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please select a customer first!");
        return; // Stops the rest of the code from running
    }

    // 2. Validation: Check if a product is selected
    if (txtProductName.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please select a product!");
        return;
    }
    
        String qtyText = txtOrderQuantity.getText().trim();
    int selectedRow = tblProduct.getSelectedRow();

    // 1. Basic Validation
    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Please select a product from the table first.");
        return;
    }
    if (qtyText.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please enter the quantity.");
        return;
    }

    try {
        int orderQty = Integer.parseInt(qtyText);
        int stockAvailable = Integer.parseInt(tblProduct.getValueAt(selectedRow, 3).toString());
        double price = Double.parseDouble(txtProductPrice.getText());

        // 2. Business Logic Validation
        if (orderQty <= 0) {
            JOptionPane.showMessageDialog(this, "Quantity must be greater than zero.");
            return;
        }
        if (orderQty > stockAvailable) {
            JOptionPane.showMessageDialog(this, "Insufficient stock! Only " + stockAvailable + " available.");
            return;
        }

        // 3. Calculation & Cart Update
        double subtotal = orderQty * price;
        int productId = (int) tblProduct.getValueAt(selectedRow, 0);
        String productName = txtProductName.getText();

        DefaultTableModel cartModel = (DefaultTableModel) tblCart.getModel();
        cartModel.addRow(new Object[]{
            productId,
            productName,
            orderQty,
            price,
            subtotal
        });

        // 4. Update the Grand Total
        updateGrandTotal();
        
        // 5. Reset Product inputs for the next item
        clearProductFields();
        tblProduct.clearSelection();

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Invalid quantity. Please enter a whole number.");
    }
    }//GEN-LAST:event_btnAddToCartActionPerformed

    private void tblProductMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblProductMouseClicked
        // TODO add your handling code here:
        int row = tblProduct.getSelectedRow();
    if (row != -1) {
        try {
            // 1. Safely get the ID using toString() to avoid casting errors
            int selectedId = Integer.parseInt(tblProduct.getValueAt(row, 0).toString());
            
            // 2. Fetch only the specific product details from the DAO
            com.inventory.dao.ProductDAO pDao = new com.inventory.dao.ProductDAO();
            com.inventory.model.Product p = pDao.getProductById(selectedId);

            if (p != null) {
                // --- PART 1: STOCK CHECKS ---
                int stock = p.getCurrentQuantity(); 
                int threshold = p.getMinThreshold(); 

                if (stock <= 0) {
                    JOptionPane.showMessageDialog(this, "OUT OF STOCK! You cannot select " + p.getName());
                    tblProduct.clearSelection();
                    return; 
                }
                
                if (stock <= p.getMinThreshold()) {
                    JOptionPane.showMessageDialog(this, "LOW STOCK ALERT: Only " + stock + " left for " + p.getName(), "Warning", JOptionPane.WARNING_MESSAGE);
                }

                // --- PART 2: EXPIRY CHECKS ---
                if (p.getExpiryDate() != null) {
                    long diff = p.getExpiryDate().getTime() - System.currentTimeMillis();
                    long days = diff / (1000 * 60 * 60 * 24);

                    if (days < 0) {
                        JOptionPane.showMessageDialog(this, "STOP: This product EXPIRED " + Math.abs(days) + " days ago!", "Expired", JOptionPane.ERROR_MESSAGE);
                        tblProduct.clearSelection();
                        return;
                    } else if (days <= 7) {
                        JOptionPane.showMessageDialog(this, "EXPIRY ALERT: " + p.getName() + " expires in " + days + " days!", "Warning", JOptionPane.WARNING_MESSAGE);
                    }
                }

                // --- PART 3: UI POPULATION ---
                txtProductName.setText(p.getName());
                txtProductPrice.setText(String.valueOf(p.getPrice()));
                // Ensure your Product model has getCategoryName()
                txtProductCategory.setText(p.getCategoryName()); 
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Selection Error: " + e.getMessage());
            e.printStackTrace();
        }
    }
    }//GEN-LAST:event_tblProductMouseClicked

    private void updateGrandTotal() {
    double total = 0;
    DefaultTableModel model = (DefaultTableModel) tblCart.getModel();
    
    for (int i = 0; i < model.getRowCount(); i++) {
        try {
            // Get the value and safely convert it to a String then to a Double
            Object value = model.getValueAt(i, 4); 
            if (value != null) {
                total += Double.parseDouble(value.toString());
            }
        } catch (Exception e) {
            System.err.println("Error calculating row " + i + ": " + e.getMessage());
        }
    }
    
    // This works for both JLabel and JTextField
    lblTotalAmount.setText("" + String.format("%.2f", total));
}
    
