    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        int index = tblProducts.getSelectedRow();
    if (index == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Select a product to delete!");
        return;
    }

    int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Delete this product?", "Confirm", javax.swing.JOptionPane.YES_NO_OPTION);
    if (confirm == javax.swing.JOptionPane.YES_OPTION) {
        int id = (Integer) tblProducts.getValueAt(index, 0);
        if (new com.inventory.dao.ProductDAO().deleteProduct(id)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Product Deleted!");
            loadTableData();
            clearFields();
        }
    }
    }//GEN-LAST:event_btnDeleteActionPerformed

