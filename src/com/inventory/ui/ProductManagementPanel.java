    private void setupTableUI() {
    tblProducts.setRowHeight(30);
    javax.swing.table.DefaultTableCellRenderer centerRenderer = new javax.swing.table.DefaultTableCellRenderer();
    centerRenderer.setHorizontalAlignment(javax.swing.JLabel.CENTER);
    
    for (int i = 0; i < tblProducts.getColumnCount(); i++) {
        tblProducts.getColumnModel().getColumn(i).setCellRenderer(centerRenderer);
    }
    ((DefaultTableCellRenderer)tblProducts.getTableHeader().getDefaultRenderer())
        .setHorizontalAlignment(javax.swing.JLabel.CENTER);
    }
    
    private void loadTableData() {
    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblProducts.getModel();
    model.setRowCount(0);

    com.inventory.dao.ProductDAO dao = new com.inventory.dao.ProductDAO();
    java.util.List<com.inventory.model.Product> list = dao.getAllProducts();

    for (com.inventory.model.Product p : list) {
        model.addRow(new Object[]{
            p.getProductId(),
            p.getName(),
            p.getCategoryName(), // Populated by the JOIN in DAO
            p.getPrice(),
            p.getCurrentQuantity(),
            p.getMinThreshold(),
            p.getExpiryDate() != null ? p.getExpiryDate().toString() : "N/A"
        });
    }
    checkAlerts(list);
    
}
    
